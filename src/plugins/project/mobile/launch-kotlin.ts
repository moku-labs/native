/**
 * @file project plugin — the generated `MokuLaunch.kt` of the Android launch still. The
 * object draws `app.launch.still` over the activity's decor view from the first frame, turns
 * the translucent start window opaque after it (Android 11+), and gives the page
 * `window.__mokuLaunch.ready()`, which removes the still once the WebView has that frame on
 * screen. Without `ready()` the still goes after `HOLD_MAX_MS` with a logcat warning. The
 * placement maths is the twin of `stillPlacement` in `launch-still.ts`, the tested reference.
 * Only the Android SDK is used; every number is a literal from the resolved config.
 */
import type { ResolvedLaunch } from "../types";
import { androidColour } from "./window-background";

/** Marks every line and file the launch still patch owns, after `//` or inside `<!-- -->`. */
export const LAUNCH_MARKER = "moku:native launch still";

/** What the generated object is made from. */
type LaunchKotlinOptions = {
  /** The package of MainActivity.kt, so the activity calls `MokuLaunch` without an import. */
  readonly packageName: string;
  /** The resolved `app.launch`. */
  readonly launch: ResolvedLaunch;
  /** `app.backgroundColor`, or undefined for white. */
  readonly backgroundColor: string | undefined;
};

/**
 * Writes a number as a Kotlin `Float` literal.
 *
 * @param value - A finite number.
 * @returns The literal with its `f` suffix.
 * @example
 * ```ts
 * floatLiteral(1024); // "1024f"
 * floatLiteral(12.5); // "12.5f"
 * ```
 */
function floatLiteral(value: number): string {
  return `${String(value)}f`;
}

/**
 * Writes an aspect bound as a Kotlin `Float` literal, six decimals; `0f` when unset, which
 * the Kotlin reads as "no aspect".
 *
 * @param value - The bound, or undefined.
 * @returns The literal.
 * @example
 * ```ts
 * aspectLiteral(4 / 3); // "1.333333f"
 * aspectLiteral(undefined); // "0f"
 * ```
 */
function aspectLiteral(value: number | undefined): string {
  return value === undefined ? "0f" : `${value.toFixed(6)}f`;
}

/**
 * Writes `app.backgroundColor` as an opaque ARGB Kotlin `Int`: the alpha is forced to `FF`,
 * since a see-through first frame would show the launcher; white when unset.
 *
 * @param colour - `#rrggbb`, `#rrggbbaa`, or undefined.
 * @returns The `0xFFRRGGBB.toInt()` expression.
 * @example
 * ```ts
 * backgroundLiteral("#10161d80"); // "0xFF10161D.toInt()"
 * ```
 */
function backgroundLiteral(colour: string | undefined): string {
  const rgb = colour === undefined ? "FFFFFF" : androidColour(colour).slice(-6).toUpperCase();
  return `0xFF${rgb}.toInt()`;
}

/**
 * Builds `MokuLaunch.kt`, the object MainActivity.kt calls from `onCreate` (`attach`) and
 * `onWebViewCreate` (`bind`).
 *
 * @param options - The package, the resolved launch and the background colour.
 * @returns The Kotlin source, LF line endings.
 * @example
 * ```ts
 * launchKotlin({ packageName: "dev.moku.v6app", launch, backgroundColor: "#F4E6CA" });
 * // "package dev.moku.v6app\n\n// moku:native launch still — generated …"
 * ```
 */
export function launchKotlin(options: LaunchKotlinOptions): string {
  const { launch } = options;
  return `package ${options.packageName}

// ${LAUNCH_MARKER} — generated by @moku-labs/native from app.launch. Do not edit.

import android.app.Activity
import android.content.Context
import android.graphics.Bitmap
import android.graphics.BitmapFactory
import android.graphics.Canvas
import android.graphics.Paint
import android.graphics.RectF
import android.os.Build
import android.util.Log
import android.view.View
import android.view.ViewGroup
import android.view.ViewTreeObserver
import android.webkit.JavascriptInterface
import android.webkit.WebView

/** The still frame the shell shows from its first frame until the page calls \`window.__mokuLaunch.ready()\`. */
object MokuLaunch {
  private const val BACKGROUND = ${backgroundLiteral(options.backgroundColor)}
  private const val FRAME_W = ${floatLiteral(launch.frame.width)}
  private const val FRAME_H = ${floatLiteral(launch.frame.height)}
  private const val RECT_X = ${floatLiteral(launch.rect.x)}
  private const val RECT_Y = ${floatLiteral(launch.rect.y)}
  private const val RECT_W = ${floatLiteral(launch.rect.width)}
  private const val RECT_H = ${floatLiteral(launch.rect.height)}
  private const val ASPECT_MIN = ${aspectLiteral(launch.aspect?.min)}
  private const val ASPECT_MAX = ${aspectLiteral(launch.aspect?.max)}
  private const val PORTRAIT = ${String(launch.orientation === "portrait")}
  private const val HOLD_MAX_MS = ${String(launch.holdMaxMs)}L
  private const val OPAQUE_AFTER_MS = 700L

  private var still: View? = null
  private var ready = false

  /** Called from MainActivity.onCreate after super.onCreate: the still is the first thing drawn. */
  fun attach(activity: Activity) {
    ready = false
    remove()
    val id = activity.resources.getIdentifier("moku_launch_still", "drawable", activity.packageName)
    val options = BitmapFactory.Options().apply { inScaled = false }
    val bitmap = BitmapFactory.decodeResource(activity.resources, id, options) ?: return
    val view = StillView(activity, bitmap)
    (activity.window.decorView as ViewGroup).addView(
      view, ViewGroup.LayoutParams(ViewGroup.LayoutParams.MATCH_PARENT, ViewGroup.LayoutParams.MATCH_PARENT)
    )
    still = view
    // The window started translucent so the system shows no splash; after the first frame it is a normal one.
    view.viewTreeObserver.addOnDrawListener(object : ViewTreeObserver.OnDrawListener {
      private var drawn = false
      override fun onDraw() {
        if (drawn) return
        drawn = true
        if (Build.VERSION.SDK_INT >= 30) view.postDelayed({ activity.setTranslucent(false) }, OPAQUE_AFTER_MS)
      }
    })
    view.postDelayed({
      if (still === view) {
        Log.w("moku", "launch: no ready() in $HOLD_MAX_MS ms, the still is removed")
        remove()
      }
    }, HOLD_MAX_MS)
  }

  /** Called from MainActivity.onWebViewCreate: the page gets \`window.__mokuLaunch.ready()\`. */
  fun bind(activity: Activity, webView: WebView) {
    webView.addJavascriptInterface(Bridge(activity, webView), "__mokuLaunch")
  }

  private fun remove() {
    val view = still ?: return
    (view.parent as? ViewGroup)?.removeView(view)
    still = null
  }

  private class Bridge(private val activity: Activity, private val webView: WebView) {
    @JavascriptInterface
    fun ready() {
      activity.runOnUiThread {
        if (ready) return@runOnUiThread
        ready = true
        // The still goes only when the WebView has that frame on screen.
        webView.postVisualStateCallback(0L, object : WebView.VisualStateCallback() {
          override fun onComplete(requestId: Long) { remove() }
        })
      }
    }
  }

  private class StillView(context: Context, private val bitmap: Bitmap) : View(context) {
    private val place = RectF()
    private val paint = Paint(Paint.FILTER_BITMAP_FLAG)

    override fun onDraw(canvas: Canvas) {
      canvas.drawColor(BACKGROUND)
      val w = width.toFloat()
      val h = height.toFloat()
      if (w <= 0f || h <= 0f) return
      // The game frame: the largest centred rectangle whose long / short side is inside the aspect range.
      var frameW = w
      var frameH = h
      if (ASPECT_MIN > 0f) {
        val short = if (PORTRAIT) w else h
        val long = if (PORTRAIT) h else w
        val ratio = long / short
        val wanted = ratio.coerceIn(ASPECT_MIN, ASPECT_MAX)
        val frameShort = if (ratio < wanted) long / wanted else short
        val frameLong = if (ratio > wanted) short * wanted else long
        frameW = if (PORTRAIT) frameShort else frameLong
        frameH = if (PORTRAIT) frameLong else frameShort
      }
      // The still's canvas covers that frame, centred; the picture lies in its rectangle.
      val k = maxOf(frameW / FRAME_W, frameH / FRAME_H)
      val left = (w - frameW) / 2f + (frameW - FRAME_W * k) / 2f + RECT_X * k
      val top = (h - frameH) / 2f + (frameH - FRAME_H * k) / 2f + RECT_Y * k
      place.set(left, top, left + RECT_W * k, top + RECT_H * k)
      canvas.drawBitmap(bitmap, null, place, paint)
    }
  }
}
`;
}
