import { existsSync } from "node:fs";
import { mkdir, mkdtemp, readFile, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import path from "node:path";
import { afterEach, beforeEach, describe, expect, it } from "vitest";

import {
  androidColour,
  applyWindowBackground,
  patchAndroidWindowBackground
} from "../../../mobile/window-background";
import { androidManifest } from "./fixtures";

/** `res/values/themes.xml` (and `values-night`) as `tauri android init` 2.12 writes it. */
const GENERATED_THEMES = [
  '<resources xmlns:tools="http://schemas.android.com/tools">',
  "    <!-- Base application theme. -->",
  '    <style name="Theme.my_app" parent="Theme.Material3.DayNight.NoActionBar">',
  "        <!-- Customize your theme here. -->",
  "    </style>",
  "</resources>",
  ""
].join("\n");

/** {@link GENERATED_THEMES} with the window and splash background items. */
const PATCHED_THEMES = [
  '<resources xmlns:tools="http://schemas.android.com/tools">',
  "    <!-- Base application theme. -->",
  '    <style name="Theme.my_app" parent="Theme.Material3.DayNight.NoActionBar">',
  '        <item name="android:windowBackground">@color/moku_window_background</item> <!-- moku:native window background -->',
  '        <item name="android:windowSplashScreenBackground" tools:targetApi="31">@color/moku_window_background</item> <!-- moku:native window background -->',
  "        <!-- Customize your theme here. -->",
  "    </style>",
  "</resources>",
  ""
].join("\n");

/** The moku-owned colour resource for `#10161d`. */
const COLOUR_FILE = [
  '<?xml version="1.0" encoding="utf-8"?>',
  "<!-- moku:native window background -->",
  "<resources>",
  '    <color name="moku_window_background">#10161d</color>',
  "</resources>",
  ""
].join("\n");

const THEMES_PATH = "/repo/.moku/tauri/src-tauri/gen/android/app/src/main/res/values/themes.xml";

/** Writes a file, creating its folders. */
const seed = async (filePath: string, content: string) => {
  await mkdir(path.dirname(filePath), { recursive: true });
  await writeFile(filePath, content, "utf8");
};

/** Converts LF line endings to CRLF. */
const toCrlf = (text: string) => text.replaceAll("\n", "\r\n");

describe("androidColour", () => {
  it("keeps #rrggbb as it is", () => {
    expect(androidColour("#10161d")).toBe("#10161d");
  });

  it("moves the alpha of #rrggbbaa to the front, where Android reads it", () => {
    expect(androidColour("#10161d80")).toBe("#8010161d");
  });

  it("refuses a value that is not a hex colour", () => {
    expect(() => androidColour("black")).toThrow(
      '[native] app.backgroundColor "black" is not a valid colour.\n  Use a hex colour such as "#10161d".'
    );
  });
});

describe("applyWindowBackground", () => {
  it("adds the window and splash backgrounds to the app theme", () => {
    expect(applyWindowBackground(GENERATED_THEMES, "Theme.my_app", true, THEMES_PATH)).toBe(
      PATCHED_THEMES
    );
  });

  it("is idempotent — a second pass changes nothing", () => {
    expect(applyWindowBackground(PATCHED_THEMES, "Theme.my_app", true, THEMES_PATH)).toBe(
      PATCHED_THEMES
    );
  });

  it("restores the generated bytes exactly when the colour is unset", () => {
    expect(applyWindowBackground(PATCHED_THEMES, "Theme.my_app", false, THEMES_PATH)).toBe(
      GENERATED_THEMES
    );
  });

  it("keeps CRLF line endings", () => {
    expect(applyWindowBackground(toCrlf(GENERATED_THEMES), "Theme.my_app", true, THEMES_PATH)).toBe(
      toCrlf(PATCHED_THEMES)
    );
    expect(applyWindowBackground(toCrlf(PATCHED_THEMES), "Theme.my_app", false, THEMES_PATH)).toBe(
      toCrlf(GENERATED_THEMES)
    );
  });

  it("patches only the style the manifest names", () => {
    const other = '    <style name="Theme.other" parent="Theme.Material3.Light">\n    </style>\n';
    const source = GENERATED_THEMES.replace("</resources>", `${other}</resources>`);
    const expected = PATCHED_THEMES.replace("</resources>", `${other}</resources>`);

    expect(applyWindowBackground(source, "Theme.other", false, THEMES_PATH)).toBe(source);
    expect(applyWindowBackground(source, "Theme.my_app", true, THEMES_PATH)).toBe(expected);
  });

  it("indents the items one level below an empty style", () => {
    const source =
      '<resources>\n  <style name="Theme.my_app" parent="P">\n  </style>\n</resources>\n';

    expect(applyWindowBackground(source, "Theme.my_app", true, THEMES_PATH)).toContain(
      '\n      <item name="android:windowBackground">'
    );
  });

  it("refuses a themes file without the app theme when a colour is set", () => {
    expect(() => applyWindowBackground(GENERATED_THEMES, "Theme.gone", true, THEMES_PATH)).toThrow(
      `[native] ${THEMES_PATH} has no <style name="Theme.gone"> to set the window background in.\n  Re-run the mobile init pass (tauri android init), or unset app.backgroundColor.`
    );
  });
});

describe("patchAndroidWindowBackground", () => {
  let dir: string;
  let genDir: string;
  let dayThemes: string;
  let nightThemes: string;
  let colourFile: string;
  let manifestPath: string;

  beforeEach(async () => {
    dir = await mkdtemp(path.join(tmpdir(), "moku-native-window-background-"));
    genDir = path.join(dir, "src-tauri", "gen", "android");
    const resDir = path.join(genDir, "app", "src", "main", "res");
    dayThemes = path.join(resDir, "values", "themes.xml");
    nightThemes = path.join(resDir, "values-night", "themes.xml");
    colourFile = path.join(resDir, "values", "moku_window_background.xml");
    manifestPath = path.join(genDir, "app", "src", "main", "AndroidManifest.xml");
    await seed(manifestPath, androidManifest());
    await seed(dayThemes, GENERATED_THEMES);
    await seed(nightThemes, GENERATED_THEMES);
  });

  afterEach(async () => {
    await rm(dir, { recursive: true, force: true });
  });

  it("writes the colour and both themes, then reports them unchanged", async () => {
    const first = await patchAndroidWindowBackground(dir, genDir, "#10161d");
    const second = await patchAndroidWindowBackground(dir, genDir, "#10161d");

    expect(first).toEqual({ patched: [colourFile, dayThemes, nightThemes], unchanged: [] });
    expect(second).toEqual({ patched: [], unchanged: [colourFile, dayThemes, nightThemes] });
    expect(await readFile(colourFile, "utf8")).toBe(COLOUR_FILE);
    expect(await readFile(dayThemes, "utf8")).toBe(PATCHED_THEMES);
    expect(await readFile(nightThemes, "utf8")).toBe(PATCHED_THEMES);
  });

  it("rewrites the colour when app.backgroundColor changes", async () => {
    await patchAndroidWindowBackground(dir, genDir, "#10161d");

    const result = await patchAndroidWindowBackground(dir, genDir, "#F4E6CA");

    expect(result).toEqual({ patched: [colourFile], unchanged: [dayThemes, nightThemes] });
    expect(await readFile(colourFile, "utf8")).toBe(COLOUR_FILE.replace("#10161d", "#F4E6CA"));
  });

  it("removes the colour and restores the generated themes when the colour is unset", async () => {
    await patchAndroidWindowBackground(dir, genDir, "#10161d");

    const result = await patchAndroidWindowBackground(dir, genDir, undefined);

    expect(result).toEqual({ patched: [colourFile, dayThemes, nightThemes], unchanged: [] });
    expect(existsSync(colourFile)).toBe(false);
    expect(await readFile(dayThemes, "utf8")).toBe(GENERATED_THEMES);
    expect(await readFile(nightThemes, "utf8")).toBe(GENERATED_THEMES);
  });

  it("leaves a never-patched tree unchanged when the colour is unset", async () => {
    const result = await patchAndroidWindowBackground(dir, genDir, undefined);

    expect(result).toEqual({ patched: [], unchanged: [dayThemes, nightThemes] });
    expect(existsSync(colourFile)).toBe(false);
  });

  it("keeps a colour file native did not write", async () => {
    const foreign =
      '<resources>\n    <color name="moku_window_background">#fff</color>\n</resources>\n';
    await seed(colourFile, foreign);

    await patchAndroidWindowBackground(dir, genDir, undefined);

    expect(await readFile(colourFile, "utf8")).toBe(foreign);
  });

  it("patches the day theme alone when there is no night theme", async () => {
    await rm(nightThemes);

    const result = await patchAndroidWindowBackground(dir, genDir, "#10161d");

    expect(result).toEqual({ patched: [colourFile, dayThemes], unchanged: [] });
  });

  it("throws without a manifest theme when a colour is set, and does nothing when unset", async () => {
    await seed(manifestPath, androidManifest().replace(' android:theme="@style/Theme.my_app"', ""));

    await expect(patchAndroidWindowBackground(dir, genDir, "#10161d")).rejects.toThrow(
      `[native] ${manifestPath} names no android:theme on <application> to set the window background in.\n  Re-run the mobile init pass (tauri android init), or unset app.backgroundColor.`
    );
    await expect(patchAndroidWindowBackground(dir, genDir, undefined)).resolves.toEqual({
      patched: [],
      unchanged: [dayThemes, nightThemes]
    });
  });

  it("throws without the day themes file when a colour is set", async () => {
    await rm(dayThemes);

    await expect(patchAndroidWindowBackground(dir, genDir, "#10161d")).rejects.toThrow(
      `[native] ${dayThemes} not found.\n  Re-run the mobile init pass (tauri android init), or unset app.backgroundColor.`
    );
  });
});
