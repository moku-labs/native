/**
 * @file project plugin generator — the shell crate's Rust side: `Cargo.toml`, `build.rs`,
 * `src/lib.rs` and `permissions/default.toml`.
 */
import type { Artifact } from "../types";

/**
 * The shell's six commands, as the page invokes them (`plugin:moku-shell|<command>`). One
 * list feeds `build.rs` (which generates `allow-<command>`), `permissions/default.toml`
 * (which grants them) and the handler in `lib.rs`, so a command can never be declared but
 * denied, or granted but missing.
 */
export const SHELL_COMMANDS = [
  "set_frame_rate",
  "thermal",
  "insets",
  "log",
  "share",
  "info"
] as const;

/** The Kotlin package of the plugin class — also the Android module's namespace. */
export const SHELL_ANDROID_PACKAGE = "app.moku.shell";

/** The first line of every generated source file of the crate, behind its comment marker. */
export const SHELL_GENERATED_NOTICE =
  "Generated by @moku-labs/native on every build — edit the generator, not this file.";

/** The crate's package name — `links` must carry it too, or the Tauri CLI never finds the Android library. */
const CRATE_NAME = "tauri-plugin-moku-shell";

/** The Kotlin method each command forwards to (`run_mobile_plugin` calls it by name). */
const KOTLIN_METHOD: Readonly<Record<(typeof SHELL_COMMANDS)[number], string>> = {
  set_frame_rate: "setFrameRate",
  thermal: "thermal",
  insets: "insets",
  log: "log",
  share: "share",
  info: "info"
};

/** The Rust arguments each command takes, as `name: Type` pairs; JSON keys are the names. */
const COMMAND_ARGUMENTS: Readonly<
  Record<(typeof SHELL_COMMANDS)[number], ReadonlyArray<readonly [string, string]>>
> = {
  set_frame_rate: [["fps", "Option<f64>"]],
  thermal: [],
  insets: [],
  log: [
    ["level", "String"],
    ["message", "String"]
  ],
  share: [
    ["name", "String"],
    ["mime", "String"],
    ["bytes", "String"]
  ],
  info: []
};

/**
 * Names the permission `build.rs` generates for one command.
 *
 * @param command - A command name.
 * @returns Its `allow-` permission id, kebab-cased.
 * @example
 * ```ts
 * allowPermission("set_frame_rate"); // "allow-set-frame-rate"
 * ```
 */
function allowPermission(command: string): string {
  return `allow-${command.replaceAll("_", "-")}`;
}

/**
 * Renders one quoted, comma-separated list of the commands in the given form.
 *
 * @param format - Maps a command name to its listed form.
 * @returns The items, each double-quoted, joined with `", "`.
 * @example
 * ```ts
 * quotedCommands(command => command); // '"set_frame_rate", "thermal", "insets", "log", "share", "info"'
 * ```
 */
function quotedCommands(format: (command: string) => string): string {
  return SHELL_COMMANDS.map(command => `"${format(command)}"`).join(", ");
}

/**
 * Renders the `#[tauri::command]` that forwards one command, with its arguments, to the
 * Kotlin plugin.
 *
 * @param command - One of {@link SHELL_COMMANDS}.
 * @returns The Rust source of the command function.
 * @example
 * ```ts
 * rustCommand("thermal"); // '#[tauri::command]\nasync fn thermal<R: Runtime>(app: AppHandle<R>) -> …'
 * ```
 */
function rustCommand(command: (typeof SHELL_COMMANDS)[number]): string {
  const parameters = COMMAND_ARGUMENTS[command]
    .map(([name, type]) => `, ${name}: ${type}`)
    .join("");
  const payload = COMMAND_ARGUMENTS[command].map(([name]) => `"${name}": ${name}`).join(", ");
  return [
    "#[tauri::command]",
    `async fn ${command}<R: Runtime>(app: AppHandle<R>${parameters}) -> Result<Value, String> {`,
    `  forward(&app, "${KOTLIN_METHOD[command]}", serde_json::json!({ ${payload} }))`,
    "}"
  ].join("\n");
}

/** `Cargo.toml`: `links` is mandatory for a Tauri plugin crate (research Q1). */
const CARGO_TOML = [
  `# ${SHELL_GENERATED_NOTICE}`,
  "[package]",
  `name = "${CRATE_NAME}"`,
  'version = "1.0.0"',
  'edition = "2021"',
  `links = "${CRATE_NAME}"`,
  "publish = false",
  "",
  "[dependencies]",
  'tauri = { version = "2.12" }',
  'serde = "1"',
  'serde_json = "1"',
  "",
  "[build-dependencies]",
  'tauri-plugin = { version = "2", features = ["build"] }',
  ""
].join("\n");

/** `build.rs`: generates `allow-<command>` per command and wires the Android module. */
const BUILD_RS = [
  `// ${SHELL_GENERATED_NOTICE}`,
  `const COMMANDS: &[&str] = &[${quotedCommands(command => command)}];`,
  "",
  "fn main() {",
  "  // No ios_path while the iOS shell is deferred (Decision D6).",
  '  tauri_plugin::Builder::new(COMMANDS).android_path("android").build();',
  "}",
  ""
].join("\n");

/** `permissions/default.toml`: the `moku-shell:default` set the app's capability grants. */
const DEFAULT_TOML = [
  `# ${SHELL_GENERATED_NOTICE}`,
  "[default]",
  'description = "Every command of the moku shell: frame rate, thermal, insets, console log, share and device info."',
  `permissions = [${quotedCommands(allowPermission)}]`,
  ""
].join("\n");

/** `src/lib.rs`: the plugin — page script, Kotlin registration, six forwarding commands. */
const LIB_RS = [
  `// ${SHELL_GENERATED_NOTICE}`,
  "use serde_json::Value;",
  "use tauri::{",
  "  plugin::{Builder, TauriPlugin},",
  "  AppHandle, Runtime,",
  "};",
  "",
  '#[cfg(target_os = "android")]',
  "use tauri::{plugin::PluginHandle, Manager};",
  "",
  "/// The page contract `globalThis.__MOKU_NATIVE__` v1, run before page scripts in the main frame",
  "/// (Tauri 2.12 injects plugin init scripts there only; an iframe may lack __TAURI_INTERNALS__).",
  'const PAGE_SCRIPT: &str = include_str!("page.js");',
  "",
  "/// The Kotlin side of the shell, registered at setup.",
  '#[cfg(target_os = "android")]',
  "struct MokuShell<R: Runtime>(PluginHandle<R>);",
  "",
  "/// Forwards one command and its arguments to the Kotlin plugin.",
  '#[cfg(target_os = "android")]',
  "fn forward<R: Runtime>(app: &AppHandle<R>, command: &str, args: Value) -> Result<Value, String> {",
  "  app",
  "    .state::<MokuShell<R>>()",
  "    .0",
  "    .run_mobile_plugin(command, args)",
  "    .map_err(|error| error.to_string())",
  "}",
  "",
  "/// Off Android there is no shell to answer.",
  '#[cfg(not(target_os = "android"))]',
  "fn forward<R: Runtime>(_app: &AppHandle<R>, command: &str, _args: Value) -> Result<Value, String> {",
  '  Err(format!("moku-shell: {command} needs the Android shell"))',
  "}",
  "",
  ...SHELL_COMMANDS.flatMap(command => [rustCommand(command), ""]),
  "/// The moku shell: the page contract script, the Kotlin plugin and its commands.",
  "pub fn init<R: Runtime>() -> TauriPlugin<R> {",
  '  Builder::new("moku-shell")',
  "    .js_init_script(PAGE_SCRIPT.to_string())",
  `    .invoke_handler(tauri::generate_handler![${SHELL_COMMANDS.join(", ")}])`,
  "    .setup(|_app, _api| {",
  '      #[cfg(target_os = "android")]',
  "      {",
  `        let handle = _api.register_android_plugin("${SHELL_ANDROID_PACKAGE}", "MokuShellPlugin")?;`,
  "        _app.manage(MokuShell(handle));",
  "      }",
  "      Ok(())",
  "    })",
  "    .build()",
  "}",
  ""
].join("\n");

/**
 * Generates the shell crate's Rust and permission files, paths relative to the crate root.
 * They carry no app input: the page script, which does, is `src/page.js` beside them.
 *
 * @returns Artifacts for `Cargo.toml`, `build.rs`, `src/lib.rs` and `permissions/default.toml`.
 * @example
 * ```ts
 * shellRustArtifacts().map(artifact => artifact.path);
 * // ["Cargo.toml", "build.rs", "src/lib.rs", "permissions/default.toml"]
 * ```
 */
export function shellRustArtifacts(): Artifact[] {
  return [
    { path: "Cargo.toml", content: CARGO_TOML },
    { path: "build.rs", content: BUILD_RS },
    { path: "src/lib.rs", content: LIB_RS },
    { path: "permissions/default.toml", content: DEFAULT_TOML }
  ];
}
